/// Represents types of tokens found in lox source text.
pub const TokenType = enum(u8) {
    // Single-character tokens
    paren_left,
    paren_right,
    brace_left,
    brace_right,
    comma,
    dot,
    semicolon,
    question,
    colon,
    minus,
    plus,
    slash,
    star,

    // One or two character tokens
    bang,
    bang_equal,
    equal,
    equal_equal,
    greater,
    greater_equal,
    less,
    less_equal,
    plus_equal,
    minus_equal,
    star_equal,
    slash_equal,
    arrow,
    nilish,
    nilish_equal,

    // Literals
    identifier,
    string,
    number,

    // Keywords
    keyword_and,
    keyword_break,
    keyword_case,
    keyword_continue,
    keyword_class,
    keyword_default,
    keyword_else,
    keyword_false,
    keyword_for,
    keyword_fun,
    keyword_if,
    keyword_nil,
    keyword_or,
    keyword_print,
    keyword_return,
    keyword_super,
    keyword_switch,
    keyword_this,
    keyword_true,
    keyword_var,
    keyword_while,

    // Special
    eof,
    @"error",
};
